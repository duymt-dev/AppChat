// Sinh packages/ui/src/icons/paths.ts từ sprite SVG của prototype (L396–455). Chạy lại khi prototype đổi icon.
import fs from 'node:fs';
const html = fs.readFileSync('coding-packs/docs/06-prototype/AppChat.dc.html', 'utf8');
const re = /<symbol id="(ic-[a-z0-9-]+|lg-[a-z0-9-]+)" viewBox="([^"]+)">([\s\S]*?)<\/symbol>/g;
const seen = new Map();
for (const m of html.matchAll(re)) if (!seen.has(m[1])) seen.set(m[1], { viewBox: m[2], body: m[3] });
// Icon vẽ inline trong template prototype (không nằm trong sprite)
const INLINE = { 'ic-chevron-right': { viewBox: '0 0 24 24', body: '<path d="M9 6l6 6-6 6"/>' } };
for (const [id, v] of Object.entries(INLINE)) if (!seen.has(id)) seen.set(id, v);
const lines = ['// AUTO-GENERATED by tools/scripts/gen-icons.mjs from prototype sprite — do not edit.', '', 'export const ICONS = {'];
for (const [id, { viewBox, body }] of seen) lines.push(`  '${id}': { viewBox: '${viewBox}', body: ${JSON.stringify(body)} },`);
lines.push('} as const;', '', 'export type IconName = keyof typeof ICONS;', '');
fs.mkdirSync('packages/ui/src/icons', { recursive: true });
fs.writeFileSync('packages/ui/src/icons/paths.ts', lines.join('\n'));
console.log(`icons: ${[...seen.keys()].filter((k) => k.startsWith('ic-')).length} ic + ${[...seen.keys()].filter((k) => k.startsWith('lg-')).length} lg`);
